/**
 * Generates src/generators/shared/fontMetrics.ts from the TTFs in public/fonts.
 * Advance widths (in em) for printable ASCII, per font face, so text can be
 * measured identically in the browser, the CLI and tests.
 *   npm run fonts:metrics
 */
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const faces = [
  ["serif", "Lora"],
  ["sans", "Inter"],
  ["mono", "JetBrainsMono"],
  ["grotesk", "SchibstedGrotesk"],
  ["display", "InstrumentSerif"],
] as const;

const out: string[] = [];
for (const [key, file] of faces) {
  for (const style of ["Regular", "Italic"] as const) {
    const buf = readFileSync(`public/fonts/${file}-${style}.ttf`);
    const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    const widths: number[] = [];
    for (let c = 32; c < 127; c++) {
      const g = font.charToGlyph(String.fromCharCode(c));
      widths.push(Math.round(((g.advanceWidth ?? 0) / font.unitsPerEm) * 1000) / 1000);
    }
    const names = font.names as unknown as Record<string, { fontFamily?: { en?: string } } | undefined> & { fontFamily?: { en?: string } };
    const family = names.windows?.fontFamily?.en ?? names.macintosh?.fontFamily?.en ?? names.fontFamily?.en ?? file;
    out.push(`  "${key}-${style.toLowerCase()}": { family: ${JSON.stringify(family)}, widths: [${widths.join(",")}] },`);
  }
}

writeFileSync(
  "src/generators/shared/fontMetrics.ts",
  `// GENERATED by scripts/font-metrics.ts — do not edit.\n` +
    `export interface FaceMetrics { family: string; widths: readonly number[] }\n` +
    `export const FONT_METRICS: Record<string, FaceMetrics> = {\n${out.join("\n")}\n};\n`,
);
console.log("wrote src/generators/shared/fontMetrics.ts");
