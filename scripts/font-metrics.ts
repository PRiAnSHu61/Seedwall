/**
 * Generates src/generators/shared/fontMetrics.ts from the TTFs in public/fonts.
 * Advance widths (in em) for printable ASCII (and Devanagari where present), per font face, so text can be
 * measured identically in the browser, the CLI and tests.
 *   npm run fonts:metrics
 */
import { readFileSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import opentype from "opentype.js";

const faces = [
  ["serif", "Lora"],
  ["sans", "Inter"],
  ["mono", "JetBrainsMono"],
  ["grotesk", "SchibstedGrotesk"],
  ["display", "InstrumentSerif"],
  ["hindi", "TiroDevanagariHindi"],
] as const;

const out: string[] = [];
for (const [key, file] of faces) {
  for (const style of ["Regular", "Italic"] as const) {
    const buf = readFileSync(`public/fonts/${file}-${style}.ttf`);
    const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    const widths: number[] = [];
    for (let c = 32; c < 127; c++) {
      const g = font.charToGlyph(String.fromCharCode(c));
      widths.push(Math.round(((g.advanceWidth ?? 0) / font.unitsPerEm) * 1000) / 1000);
    }
    // Devanagari (U+0900–U+097F) for faces that have it, so Hindi lines centre properly.
    let deva = "";
    if (font.charToGlyph("\u0915").index > 0) {
      const dw: number[] = [];
      for (let c = 0x900; c < 0x980; c++) {
        const g = font.charToGlyph(String.fromCharCode(c));
        dw.push(g.index > 0 ? Math.round(((g.advanceWidth ?? 0) / font.unitsPerEm) * 1000) / 1000 : 0.56);
      }
      // Conjuncts (consonant + virama + consonant) are narrower than their parts. Measure each pair as
      // rendered and store the difference, so measure() can correct the plain sum of advances.
      const file2 = `public/fonts/${file}-${style}.ttf`;
      const ink = (t: string): number => {
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="4000" height="400"><text x="10" y="200" font-family="X" font-size="100">${t}</text></svg>`;
        const r = new Resvg(svg, { font: { fontFiles: [file2], loadSystemFonts: false, defaultFontFamily: "X" } });
        return r.getBBox()?.width ?? 0;
      };
      const hh = ink("\u0915\u0915");
      const adv = (c: number) => dw[c - 0x900] ?? 0;
      const conj: number[] = [];
      for (let a = 0x915; a <= 0x939; a++)
        for (let b = 0x915; b <= 0x939; b++) {
          const shaped = (ink(`\u0915${String.fromCharCode(a, 0x94d, b)}\u0915`) - hh) / 100;
          conj.push(Math.round((shaped - adv(a) - adv(0x94d) - adv(b)) * 1000) / 1000);
        }
      deva = `, deva: [${dw.join(",")}], conj: [${conj.join(",")}]`;
    }
    const names = font.names as unknown as Record<string, { fontFamily?: { en?: string } } | undefined> & { fontFamily?: { en?: string } };
    const family = names.windows?.fontFamily?.en ?? names.macintosh?.fontFamily?.en ?? names.fontFamily?.en ?? file;
    out.push(`  "${key}-${style.toLowerCase()}": { family: ${JSON.stringify(family)}, widths: [${widths.join(",")}]${deva} },`);
  }
}

writeFileSync(
  "src/generators/shared/fontMetrics.ts",
  `// GENERATED by scripts/font-metrics.ts — do not edit.\n` +
    `export interface FaceMetrics { family: string; widths: readonly number[]; deva?: readonly number[]; conj?: readonly number[] }\n` +
    `export const FONT_METRICS: Record<string, FaceMetrics> = {\n${out.join("\n")}\n};\n`,
);
console.log("wrote src/generators/shared/fontMetrics.ts");
